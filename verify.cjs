const fs = require('node:fs');
const vm = require('node:vm');
const assert = require('node:assert/strict');
const elements = new Proxy({}, {get: (object, key) => object[key] ??= {addEventListener() {}, value: '', textContent: ''}});
const root = {dataset: {theme: 'light'}};
const saved = new Map();
const context = vm.createContext({t:text=>text,document: {documentElement: root, getElementById: id => { const element = elements[id]; element.setAttribute = () => {}; return element; }}, localStorage: {setItem: (k,v) => saved.set(k,v)}, setTimeout, clearTimeout});
vm.runInContext(fs.readFileSync('public/app.js', 'utf8'), context);
context.sample = '1\n00:00:01,000 --> 00:00:03,500\nOlá\n\n2\n00:00:04,000 --> 00:00:06,000\nMundo';
assert.equal(vm.runInContext('parseCaptions(sample).length', context), 2);
assert.equal(vm.runInContext('parseCaptions(sample)[0].duration', context), 2.5);
context.sample = 'WEBVTT\n\n00:01.000 --> 00:03.000 align:start\n<b>Olá</b>';
assert.equal(vm.runInContext('parseCaptions(sample)[0].text', context), 'Olá');
assert.equal(vm.runInContext('srtClock(3661.125)', context), '01:01:01,125');
assert.equal(vm.runInContext('parseCaptions("invalid").length', context), 0);
console.log('SRT/VTT import, invalid input and export timing OK');
elements['theme-toggle'].onclick();
assert.equal(root.dataset.theme, 'dark');
assert.equal(saved.get('fio-theme'), 'dark');
context.matchMedia = () => ({matches: false});
context.localStorage.getItem = k => saved.get(k);
vm.runInContext(fs.readFileSync('public/theme.js', 'utf8'), context);
assert.equal(root.dataset.theme, 'dark');
elements['theme-toggle'].onclick();
assert.equal(root.dataset.theme, 'light');
console.log('Theme toggle, persistence and restoration OK');
